#!/usr/bin/env bash
# Regenerates everything derived from the OpenXR headers and registry: the ABI
# bindings, then the runtime's dispatch table. Rerun after bumping the SDK
# submodule or editing packages/rust/runtime/extensions.txt.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
include="$root/build/openxr-sdk/include"
out="$root/packages/rust/openxr-abi/src/bindings.rs"

export DEVELOPER_DIR="${DEVELOPER_DIR:-/Applications/Xcode.app/Contents/Developer}"
sdk="$(xcrun --sdk macosx --show-sdk-path)"
release="$(git -C "$root/third_party/OpenXR-SDK-Source" describe --tags)"

bindgen "$root/packages/rust/openxr-abi/wrapper.h" \
  --output "$out" \
  --allowlist-type '(Xr|PFN_xr).*' \
  --allowlist-var 'XR_.*' \
  --default-enum-style newtype \
  --no-prepend-enum-name \
  --clang-macro-fallback \
  --raw-line '// @generated by scripts/openxr-abi.sh — do not edit.' \
  --raw-line "// From the OpenXR headers of OpenXR-SDK-Source $release:" \
  --raw-line '// Copyright 2017-2026 The Khronos Group Inc.' \
  --raw-line '// SPDX-License-Identifier: Apache-2.0 OR MIT' \
  -- -I"$include" -isysroot "$sdk"

cargo run --quiet --manifest-path "$root/Cargo.toml" -p tether-openxr-gen -- \
  "$root/third_party/OpenXR-SDK-Source/specification/registry/xr.xml" \
  "$out" \
  "$root/packages/rust/runtime/extensions.txt" \
  "$root/packages/rust/runtime/src/generated.rs"
